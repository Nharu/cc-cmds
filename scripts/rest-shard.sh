#!/usr/bin/env bash
# Partition the goals of `make test-rest` into shards, longest first.
#
# THE PARTITION IS NEVER COMMITTED. Every shard job recomputes it from the
# Makefile's own `print-rest-goals` and takes its own share, so a suite added
# after the census was taken still lands somewhere. What IS committed is the
# census (`scripts/rest-census.tsv`), and a stale census costs balance, never
# coverage — the same split scripts/gate-shard.sh makes for the gate suite.
#
# THE ORDER INSIDE A SHARD IS THE START ORDER. `make rest-shard` hands this
# shard's goals to a sub-make on its command line, and a sub-make starts its
# command-line goals in the order given, as many at once as the outer -j allows.
# So the heaviest goal of a shard is printed first and starts first, and the
# runner's wall clock is not left waiting behind a long suite that started late.
#
# THE WEIGHT IS THE CENSUS SECONDS. A goal the census does not know weighs the
# lower median of the goals both the list and the census know, or 1 when there
# is none; a missing census weighs every goal 1. The median rather than the
# maximum because suites are added often here and the partitioner self-tests do
# not run under scripts/suite-guard.sh, so they are never recorded: weighing
# them at the maximum would stack several thirteen-minute ghosts onto the
# shards. The cost is that a truly long new suite is underweighed until the
# census is regenerated; the unmeasured report below and each shard job's
# duration table make that visible.
#
# THE LOAD IS LPT: heaviest goal first (ties by goal name, bytewise), onto the
# least-loaded shard (ties to the lowest shard number). The jobs each recompute
# the partition independently, and without a total order two jobs can disagree
# and a goal belongs to nobody.
#
# Usage:
#   bash scripts/rest-shard.sh --shards N --shard K    goals of shard K, heaviest
#                                                      first, space-joined
#   bash scripts/rest-shard.sh --shards N --table      K<TAB>load<TAB>goals per shard
#   bash scripts/rest-shard.sh --shards N --check [--from-table F]
#                                                      the shards' union equals the
#                                                      goal set, and no goal twice
#   bash scripts/rest-shard.sh --merge [--source TEXT] <timing file>…
#                                                      a census on stdout from the
#                                                      files suite-guard wrote under
#                                                      CC_SUITE_TIMING_DIR
#   bash scripts/rest-shard.sh --self-test
#
#   --goals-file PATH  the goal list, one per line (default: the Makefile's
#                      `print-rest-goals`)
#   --census PATH      the census to weigh with (default: scripts/rest-census.tsv;
#                      a missing file weighs every goal 1)
#   --source TEXT      the census's provenance line (run id, commit, time);
#                      `-` when absent
#
# Exit codes: 0 done, 2 usage, 3 the goals could not be listed or the check
# failed, 4 the requested shard is empty.
#
# Compatibility: bash 3.2 (macOS); the runner's awk is mawk, so no asort.

set -uo pipefail
export LC_ALL=C

script_dir=$(cd "$(dirname "$0")" && pwd)
repo_root=$(cd "$script_dir/.." && pwd)

CENSUS_HEAD='# rest-census v1 — generated by scripts/rest-shard.sh --merge; do not edit by hand'

shard_usage() {
  printf 'rest-shard: 사용법 — --shards N 와 함께 --shard K / --table / --check 중 하나, --merge <파일>…, 또는 --self-test (선택: --goals-file PATH, --census PATH, --from-table F, --source TEXT)\n' >&2
  exit 2
}

# rest_goals <out> — the goal list, one per line. The sub-make runs with the
# outer make's flags cleared so it never joins the caller's jobserver.
rest_goals() {
  local out="$1" err="$1.err"
  if [ -n "$goals_file" ]; then
    if [ ! -f "$goals_file" ]; then
      printf 'rest-shard: 목표 목록 파일이 없습니다 (%s) — 분할을 추측하지 않습니다\n' "$goals_file" >&2
      return 3
    fi
    grep -v '^[[:space:]]*$' "$goals_file" > "$out"
  elif ! MAKEFLAGS= MFLAGS= MAKELEVEL= make -s --no-print-directory -C "$repo_root" print-rest-goals < /dev/null > "$out" 2> "$err"; then
    printf 'rest-shard: 목표 목록을 얻지 못했습니다 (make print-rest-goals 실패) — 분할을 추측하지 않습니다\n' >&2
    sed 's/^/  /' "$err" >&2
    return 3
  fi
  if ! grep -q . "$out"; then
    printf 'rest-shard: 목표 목록이 비었습니다 — 분할을 추측하지 않습니다\n' >&2
    return 3
  fi
  return 0
}

# shard_partition <goals> <census> <N> — `T <K> <load> <goals>` per shard, the
# goals comma-joined heaviest first, and `U <count> <weight> <goals>` when some
# goal was unmeasured.
shard_partition() {
  local goals="$1" census="$2" shards="$3" cen
  cen="$goals.census"
  if [ -f "$census" ]; then cp "$census" "$cen"; else : > "$cen"; fi
  awk -F '\t' -v N="$shards" -v GOALS="$goals" -v CEN="$cen" '
    BEGIN {
      while ((getline line < GOALS) > 0) {
        gsub(/[ \t\r]/, "", line)
        if (line != "" && !(line in known)) { ng++; g[ng] = line; known[line] = 1 }
      }
      while ((getline line < CEN) > 0) {
        if (line ~ /^#/ || line == "") continue
        split(line, f, "\t")
        if (f[1] == "goal") continue
        if (f[2] ~ /^[0-9]+(\.[0-9]+)?$/) cw[f[1]] = f[2] + 0
      }
      # The lower median of the goals both sides know.
      nm = 0
      for (i = 1; i <= ng; i++) if (g[i] in cw) { nm++; ms[nm] = cw[g[i]] }
      for (i = 2; i <= nm; i++) { v = ms[i]; j = i - 1; while (j >= 1 && ms[j] > v) { ms[j + 1] = ms[j]; j-- } ms[j + 1] = v }
      med = (nm > 0) ? ms[int((nm + 1) / 2)] : 1
      nu = 0; ul = ""
      for (i = 1; i <= ng; i++) {
        if (g[i] in cw) w[g[i]] = cw[g[i]]
        else { w[g[i]] = med; nu++; ul = ul (nu > 1 ? " " : "") g[i] }
      }
      # Insertion sort: weight descending, goal name ascending.
      for (i = 1; i <= ng; i++) ord[i] = g[i]
      for (i = 2; i <= ng; i++) {
        v = ord[i]; j = i - 1
        while (j >= 1 && (w[ord[j]] < w[v] || (w[ord[j]] == w[v] && ord[j] > v))) { ord[j + 1] = ord[j]; j-- }
        ord[j + 1] = v
      }
      for (k = 1; k <= N; k++) { load[k] = 0; s[k] = "" }
      for (i = 1; i <= ng; i++) {
        best = 1
        for (k = 2; k <= N; k++) if (load[k] < load[best]) best = k
        load[best] += w[ord[i]]
        s[best] = s[best] (s[best] == "" ? "" : ",") ord[i]
      }
      for (k = 1; k <= N; k++) print "T\t" k "\t" load[k] "\t" s[k]
      if (nu > 0) print "U\t" nu "\t" med "\t" ul
    }
  ' < /dev/null
}

# The coverage check reads the TABLE, so a table produced elsewhere
# (`--from-table`) is held to the same rule. It compares SETS: a count is
# satisfied by one goal twice and another goal never.
shard_check() {
  local table="$1" goals="$2" tmp rc=0
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/rest-shard-check.XXXXXX")
  awk -F '\t' '{ n = split($3, a, ","); for (i = 1; i <= n; i++) if (a[i] != "") print a[i] }' "$table" > "$tmp/all"
  sort "$tmp/all" | uniq -d > "$tmp/dup"
  sort -u "$tmp/all" > "$tmp/have"
  sort -u "$goals" > "$tmp/want"
  comm -13 "$tmp/have" "$tmp/want" > "$tmp/missing"
  comm -23 "$tmp/have" "$tmp/want" > "$tmp/extra"
  if [ -s "$tmp/dup" ]; then
    rc=3; printf 'rest-shard: 두 샤드 이상에 든 목표 — %s\n' "$(tr '\n' ' ' < "$tmp/dup")" >&2
  fi
  if [ -s "$tmp/missing" ]; then
    rc=3; printf 'rest-shard: 어느 샤드에도 없는 목표 — %s\n' "$(tr '\n' ' ' < "$tmp/missing")" >&2
  fi
  if [ -s "$tmp/extra" ]; then
    rc=3; printf 'rest-shard: 목표 목록에 없는 목표가 샤드에 있음 — %s\n' "$(tr '\n' ' ' < "$tmp/extra")" >&2
  fi
  if [ "$rc" = "0" ]; then
    printf 'rest-shard: 커버리지 일치 — 목표 %s개, 샤드 합집합이 목표 집합과 같고 중복 없음\n' "$(grep -c . "$tmp/want")"
  fi
  rm -rf "$tmp"
  return "$rc"
}

# shard_merge <file>… — `<suite>\t<s>\t<rc>` lines into a census. A suite seen
# more than once keeps its largest duration, with that line's rc.
shard_merge() {
  local f
  for f in "$@"; do
    [ -f "$f" ] || { printf 'rest-shard: 소요 파일이 없습니다: %s\n' "$f" >&2; return 3; }
  done
  printf '%s\n' "$CENSUS_HEAD"
  printf '# source: %s · generated %s\n' "${merge_source:--}" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  awk -F '\t' '
    NF < 3 || $2 !~ /^[0-9]+$/ { printf "rest-shard: 형식이 아닌 소요 줄을 건너뜁니다 (%s:%d): %s\n", FILENAME, FNR, $0 > "/dev/stderr"; next }
    { goal = "run/" $1; if (!(goal in sec) || $2 + 0 > sec[goal]) { sec[goal] = $2 + 0; rc[goal] = $3 } }
    END { for (goal in sec) printf "%s\t%d\t%s\n", goal, sec[goal], rc[goal] }
  ' "$@" | sort
}

# --- self-test ---------------------------------------------------------------

shard_self_test() {
  local passed=0 failed=0 T out out2 err rc want n
  ok()  { passed=$((passed + 1)); printf 'PASS: %s\n' "$1"; }
  bad() { failed=$((failed + 1)); printf 'FAIL: %s — %s\n' "$1" "${2:-}" >&2; }
  T=$(mktemp -d "${TMPDIR:-/tmp}/rest-shard-selftest.XXXXXX")

  printf '%s\n' run/a run/b run/c run/d run/e run/f > "$T/g1"
  printf '%s\n' "$CENSUS_HEAD" '# source: selftest' \
    "run/a	50	0" "run/b	40	0" "run/c	30	0" "run/d	20	0" "run/e	10	0" "run/f	10	0" > "$T/c1.tsv"

  # (a) determinism
  out=$(bash "$0" --goals-file "$T/g1" --census "$T/c1.tsv" --shards 3 --table 2>/dev/null)
  out2=$(bash "$0" --goals-file "$T/g1" --census "$T/c1.tsv" --shards 3 --table 2>/dev/null)
  if [ -n "$out" ] && [ "$out" = "$out2" ]; then ok "(a) 같은 입력의 --table 두 번이 바이트 동일"; else bad "(a) 같은 입력의 --table 두 번이 바이트 동일" "「${out}」 대 「${out2}」"; fi

  # (b) LPT: 50→1, 40→2, 30→3, 20→3 (30<40<50), 10(e)→2 (40<50), 10(f)→1 (50=50, lowest)
  want=$(printf '1\t60\trun/a,run/f\n2\t50\trun/b,run/e\n3\t50\trun/c,run/d')
  if [ "$out" = "$want" ]; then ok "(b) LPT 배치와 샤드 안 무게 내림차순이 고정 기대값과 같다"; else bad "(b) LPT 배치와 샤드 안 무게 내림차순이 고정 기대값과 같다" "「${out}」"; fi
  out=$(bash "$0" --goals-file "$T/g1" --census "$T/c1.tsv" --shards 3 --shard 3 2>/dev/null)
  if [ "$out" = "run/c run/d" ]; then ok "(b) --shard K 는 무게 내림차순, 공백으로 이은 한 줄"; else bad "(b) --shard K 는 무게 내림차순, 공백으로 이은 한 줄" "「${out}」"; fi

  # (c) unmeasured goals: lower median of 50,40,30,20 (the census rows the list
  # also has; run/zz is in the census only and must not count) is 30.
  printf '%s\n' run/a run/b run/c run/d run/new > "$T/g2"
  printf '%s\n' "run/a	50	0" "run/b	40	0" "run/c	30	0" "run/d	20	0" "run/zz	1	0" > "$T/c2.tsv"
  err=$(bash "$0" --goals-file "$T/g2" --census "$T/c2.tsv" --shards 2 --table 2>&1 >/dev/null)
  out=$(bash "$0" --goals-file "$T/g2" --census "$T/c2.tsv" --shards 2 --table 2>/dev/null)
  if printf '%s' "$err" | grep -q '미측정 목표 1개 (무게 30 으로 적재) — run/new'; then ok "(c) 미측정 목표는 수·이름과 함께 하위 중앙값 무게로 보고된다"; else bad "(c) 미측정 목표는 수·이름과 함께 하위 중앙값 무게로 보고된다" "$err"; fi
  # c and new both weigh 30 and c sorts first: 50→1, 40→2, c→2 (70), new→1 (80), 20→2 (90)
  want=$(printf '1\t80\trun/a,run/new\n2\t90\trun/b,run/c,run/d')
  if [ "$out" = "$want" ]; then ok "(c) 미측정 목표가 중앙값 무게로 어느 샤드엔가 들어간다"; else bad "(c) 미측정 목표가 중앙값 무게로 어느 샤드엔가 들어간다" "「${out}」"; fi
  out=$(bash "$0" --goals-file "$T/g2" --census "$T/none.tsv" --shards 2 --table 2>/dev/null)
  want=$(printf '1\t3\trun/a,run/c,run/new\n2\t2\trun/b,run/d')
  if [ "$out" = "$want" ]; then ok "(c) 기록 파일이 없으면 모든 무게가 1"; else bad "(c) 기록 파일이 없으면 모든 무게가 1" "「${out}」"; fi

  # (d) the check compares sets
  if bash "$0" --goals-file "$T/g1" --census "$T/c1.tsv" --shards 3 --check > /dev/null 2>&1; then ok "(d) --check 가 합집합 = 목표 집합을 확인한다"; else bad "(d) --check 가 합집합 = 목표 집합을 확인한다" "비영 종료"; fi
  printf '1\t1\trun/a,run/b\n2\t1\trun/c,run/d,run/d\n3\t1\trun/e\n' > "$T/badtable"
  err=$(bash "$0" --goals-file "$T/g1" --shards 3 --check --from-table "$T/badtable" 2>&1 >/dev/null); rc=$?
  if [ "$rc" = "3" ] && printf '%s' "$err" | grep -q '두 샤드 이상에 든 목표 — run/d' && printf '%s' "$err" | grep -q '어느 샤드에도 없는 목표 — run/f'; then
    ok "(d) 중복과 누락을 집합으로 잡는다 (개수가 같아도)"
  else
    bad "(d) 중복과 누락을 집합으로 잡는다 (개수가 같아도)" "rc=$rc err=$err"
  fi

  # (e) an empty shard is exit 4, not an empty list
  bash "$0" --goals-file "$T/g1" --census "$T/c1.tsv" --shards 9 --shard 9 > /dev/null 2>&1; rc=$?
  if [ "$rc" = "4" ]; then ok "(e) 빈 샤드의 --shard 는 exit 4"; else bad "(e) 빈 샤드의 --shard 는 exit 4" "rc=$rc"; fi

  # (f) no goal list, no partition
  bash "$0" --goals-file "$T/no-such-goals" --shards 2 --table > /dev/null 2>&1; rc=$?
  if [ "$rc" = "3" ]; then ok "(f) 목표 목록을 얻지 못하면 exit 3"; else bad "(f) 목표 목록을 얻지 못하면 exit 3" "rc=$rc"; fi
  printf '\n\n' > "$T/g-empty"
  bash "$0" --goals-file "$T/g-empty" --shards 2 --check > /dev/null 2>&1; rc=$?
  if [ "$rc" = "3" ]; then ok "(f) 목표 목록이 비면 exit 3"; else bad "(f) 목표 목록이 비면 exit 3" "rc=$rc"; fi

  # (g) merge: the duplicate keeps its maximum, every suite becomes run/<suite>
  printf 'scripts/test-x.sh\t12\t0\nscripts/test-y.sh\t5\t1\n' > "$T/t1"
  printf 'scripts/test-x.sh\t30\t2\n' > "$T/t2"
  out=$(bash "$0" --merge --source 'run 1 · commit abc' "$T/t1" "$T/t2" 2>/dev/null)
  if [ "$(printf '%s\n' "$out" | sed -n 1p)" = "$CENSUS_HEAD" ] \
    && printf '%s\n' "$out" | sed -n 2p | grep -q '^# source: run 1 · commit abc · generated '; then
    ok "(g) --merge 의 첫 두 줄이 기록 파일 머리와 원천"
  else
    bad "(g) --merge 의 첫 두 줄이 기록 파일 머리와 원천" "$out"
  fi
  want=$(printf 'run/scripts/test-x.sh\t30\t2\nrun/scripts/test-y.sh\t5\t1')
  if [ "$(printf '%s\n' "$out" | sed -n '3,$p')" = "$want" ]; then ok "(g) --merge 가 중복 스위트를 최댓값으로 합치고 run/ 목표로 바꾼다"; else bad "(g) --merge 가 중복 스위트를 최댓값으로 합치고 run/ 목표로 바꾼다" "$out"; fi
  printf '%s\n' "$out" > "$T/c3.tsv"
  printf '%s\n' run/scripts/test-x.sh run/scripts/test-y.sh > "$T/g3"
  out=$(bash "$0" --goals-file "$T/g3" --census "$T/c3.tsv" --shards 1 --shard 1 2>/dev/null)
  if [ "$out" = "run/scripts/test-x.sh run/scripts/test-y.sh" ]; then ok "(g) --merge 의 출력을 그대로 기록 파일로 읽는다"; else bad "(g) --merge 의 출력을 그대로 기록 파일로 읽는다" "「${out}」"; fi

  # (h) the wrapper records the duration. The outer jobserver fds are closed so
  # the inner wrapper's sweep is about this throwaway suite alone.
  printf '#!/usr/bin/env bash\nexit 3\n' > "$T/fail3.sh"
  mkdir "$T/timing" "$T/timing-off"
  CC_SUITE_TIMING_DIR="$T/timing" CC_SUITE_GUARD_STRICT= \
    bash "$repo_root/scripts/suite-guard.sh" "$T/fail3.sh" > /dev/null 2> "$T/h.err" 3>&- 4>&- 5>&-; rc=$?
  if [ "$rc" = "3" ]; then ok "(h) 소요를 기록해도 래퍼는 스위트의 rc 3 을 그대로 돌려준다"; else bad "(h) 소요를 기록해도 래퍼는 스위트의 rc 3 을 그대로 돌려준다" "rc=$rc"; fi
  n=$(find "$T/timing" -type f | grep -c .)
  if [ "$n" = "1" ] && awk -F '\t' -v s="$T/fail3.sh" 'NR == 1 && NF == 3 && $1 == s && $2 ~ /^[0-9]+$/ && $3 == "3" { f = 1 } END { exit !(f && NR == 1) }' "$T"/timing/*; then
    ok "(h) CC_SUITE_TIMING_DIR 에 그 스위트·정수 초·rc 3 한 줄이 생긴다"
  else
    bad "(h) CC_SUITE_TIMING_DIR 에 그 스위트·정수 초·rc 3 한 줄이 생긴다" "파일 ${n}개: $(cat "$T"/timing/* 2>/dev/null)"
  fi
  if grep -qE '^suite-guard\[.*fail3\.sh\]: 종료 rc=3 소요 [0-9]+s$' "$T/h.err"; then ok "(h) stderr 에 종료 줄이 있다"; else bad "(h) stderr 에 종료 줄이 있다" "$(cat "$T/h.err")"; fi
  env -u CC_SUITE_TIMING_DIR CC_SUITE_GUARD_STRICT= TMPDIR="$T/timing-off" \
    bash "$repo_root/scripts/suite-guard.sh" "$T/fail3.sh" > /dev/null 2>&1 3>&- 4>&- 5>&-
  n=$(find "$T/timing" "$T/timing-off" -type f -name 'suite.*' | grep -c .)
  if [ "$n" = "1" ]; then ok "(h) 대조: 변수가 없으면 소요 파일이 생기지 않는다"; else bad "(h) 대조: 변수가 없으면 소요 파일이 생기지 않는다" "suite.* 파일 ${n}개"; fi
  : > "$T/not-a-dir"
  CC_SUITE_TIMING_DIR="$T/not-a-dir" CC_SUITE_GUARD_STRICT= \
    bash "$repo_root/scripts/suite-guard.sh" "$T/fail3.sh" > /dev/null 2>&1 3>&- 4>&- 5>&-; rc=$?
  if [ "$rc" = "3" ] && [ ! -s "$T/not-a-dir" ]; then ok "(h) 디렉터리가 아니면 아무것도 쓰지 않고 rc 도 그대로"; else bad "(h) 디렉터리가 아니면 아무것도 쓰지 않고 rc 도 그대로" "rc=$rc"; fi

  rm -rf "$T"
  printf 'rest-shard self-test: %d passed, %d failed\n' "$passed" "$failed"
  # A floor on the count, so a refactor that silently skips cases cannot pass.
  if [ "$passed" -lt 19 ]; then
    printf 'rest-shard self-test: 통과 수 %d 가 하한 19 에 못 미칩니다\n' "$passed" >&2
    return 1
  fi
  [ "$failed" = "0" ]
}

# --- main --------------------------------------------------------------------

goals_file=""
census="$repo_root/scripts/rest-census.tsv"
shards=""
mode=""
shard_k=""
from_table=""
merge_source=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --goals-file) [ "$#" -ge 2 ] || shard_usage; goals_file="$2"; shift 2 ;;
    --census)     [ "$#" -ge 2 ] || shard_usage; census="$2"; shift 2 ;;
    --shards)     [ "$#" -ge 2 ] || shard_usage; shards="$2"; shift 2 ;;
    --shard)      [ "$#" -ge 2 ] || shard_usage; mode="shard"; shard_k="$2"; shift 2 ;;
    --table)      mode="table"; shift ;;
    --check)      mode="check"; shift ;;
    --from-table) [ "$#" -ge 2 ] || shard_usage; from_table="$2"; shift 2 ;;
    --source)     [ "$#" -ge 2 ] || shard_usage; merge_source="$2"; shift 2 ;;
    --merge)      mode="merge"; shift; break ;;
    --self-test)  mode="self-test"; shift ;;
    *) printf 'rest-shard: 모르는 인자입니다: %s\n' "$1" >&2; shard_usage ;;
  esac
done

if [ "$mode" = "self-test" ]; then
  shard_self_test
  exit $?
fi
if [ "$mode" = "merge" ]; then
  if [ "${1:-}" = "--source" ]; then
    [ "$#" -ge 2 ] || shard_usage
    merge_source="$2"; shift 2
  fi
  [ "$#" -ge 1 ] || shard_usage
  shard_merge "$@"
  exit $?
fi
[ -n "$mode" ] || shard_usage
case "$shards" in ''|*[!0-9]*|0) shard_usage ;; esac
if [ "$mode" = "shard" ]; then
  case "$shard_k" in ''|*[!0-9]*|0) shard_usage ;; esac
  [ "$shard_k" -le "$shards" ] || shard_usage
fi

work=$(mktemp -d "${TMPDIR:-/tmp}/rest-shard-main.XXXXXX")
trap 'rm -rf "$work"' EXIT
rest_goals "$work/goals" || exit $?
shard_partition "$work/goals" "$census" "$shards" > "$work/out"
sed -n 's/^T	//p' "$work/out" > "$work/table"
awk -F '\t' '$1 == "U" { printf "rest-shard: 미측정 목표 %s개 (무게 %s 으로 적재) — %s\n", $2, $3, $4 }' "$work/out" >&2

case "$mode" in
  table) cat "$work/table" ;;
  shard)
    goals=$(awk -F '\t' -v k="$shard_k" '$1 == k { gsub(/,/, " ", $3); print $3 }' "$work/table")
    if [ -z "$goals" ]; then
      printf 'rest-shard: 샤드 %s/%s 가 비었습니다\n' "$shard_k" "$shards" >&2
      exit 4
    fi
    printf '%s\n' "$goals" ;;
  check)
    if [ -n "$from_table" ]; then
      shard_check "$from_table" "$work/goals"
    else
      shard_check "$work/table" "$work/goals"
    fi
    exit $? ;;
esac
